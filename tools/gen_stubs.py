"""Generate the type stubs of the jita architecture packages.

    uv run python tools/gen_stubs.py            write the stubs
    uv run python tools/gen_stubs.py --check    exit 1 if a stub is stale

The mnemonic functions are created at import time from the DynASM
template tables, so a type checker cannot see them. This script writes
`insns.pyi` and `__init__.pyi` for `jita.x64` and `jita.aarch64`, with one
`@overload` per accepted combination of operand classes (register width
classes, sized memory classes, immediates, labels, ...).

The real encoder decides what is accepted. For every mnemonic and arity
the script tries each tuple of operand classes with a few representative
operands per class, and a tuple becomes part of the stub if any
combination of representatives encodes. Tuples that differ in one
position are then merged into unions. So the stubs accept only what the
encoder accepts for some operands of those classes; value checks
(immediate ranges, specific registers) stay runtime errors.

`tests/test_typing.py` checks that the checked-in stubs match a fresh
generation and runs pyright and mypy over a corpus built from the same
accepted tuples (`corpus`).
"""

