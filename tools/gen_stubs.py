# -- accepted corpus -----------------------------------------------------------

X64_EXPR = {
    "Gp8": "bl", "Gp16": "bx", "Gp32": "ebx", "Gp64": "rbx", "Xmm": "xmm1", "Ymm": "ymm1",
    "St": "st1", "Mem8": "byte[rbx]", "Mem16": "word[rbx]", "Mem32": "dword[rbx]",
    "Mem64": "qword[rbx]", "Mem80": "tword[rbx]", "Mem128": "oword[rbx]",
    "Mem256": "yword[rbx]", "MemAny": "ptr[rbx]", "int": "1", "Target": '"lbl"',
}  # fmt: skip
A64_EXPR = {
    "X": "x1", "W": "w1", "Sp": "sp", "S": "s1", "D": "d1", "Q": "q1",
    "RegModX": "(x2 << 3)", "RegModW": "w2.uxtw()", "Mod": 'Mod("lsl", 16)', "int": "1",
    "float": "1.5", "Mem": "mem[x3]", "Target": '"lbl"', "Cond": '"eq"', "Bti": '"c"',
}  # fmt: skip


def _calls(fn: str, points: Iterable[Point], expr: dict[str, str]) -> list[str]:
    return [f"{fn}({', '.join(expr[c] for c in p)})" for p in points]


def _corpus_file(arch: str, calls: list[str]) -> str:
    # Calls go into functions of 50 lines: pyright checks a long module
    # level flow several times slower.
    out = [
        HEADER.rstrip(),
        f'"""Accepted {arch} calls, one per accepted class tuple (tools/gen_stubs.py)."""',
        "",
        "from jita import Assembler",
        f"from jita.{arch} import *  # noqa: F403",
        "",
        f'a = Assembler("{arch}")',
    ]
    for i in range(0, len(calls), 50):
        out += ["", "", f"def _calls{i // 50}() -> None:"]
        out += [f"    {c}" for c in calls[i : i + 50]]
    return "\n".join(out) + "\n"


def corpus() -> dict[str, str]:
    """File name -> source of the accepted corpus: one call per accepted
    class tuple, as a module function and as an assembler method. Every
    call must type check."""
    x, a = x64_oracle(), a64_oracle()
    xc: list[str] = []
    for py, per_n in sorted(x.points.items()):
        pts = [p for n in sorted(per_n) for p in per_n[n]]
        xc += _calls(py, pts, X64_EXPR) + _calls(f"a.{py}", pts, X64_EXPR)
        if py in x.short:
            xc += _calls(f"{py}.short", x.short[py], X64_EXPR) + _calls(f"a.{py}.short", x.short[py], X64_EXPR)
    xc += _calls("a.int", x.points["int_"][1], X64_EXPR)
    ac: list[str] = []
    for py, per_n in sorted(a.points.items()):
        pts = [p for n in sorted(per_n) for p in per_n[n]]
        ac += _calls(py, pts, A64_EXPR) + _calls(f"a.{py}", pts, A64_EXPR)
    for c, pts in a.cond.items():
        ac += _calls(f"b.{c}", pts, A64_EXPR) + _calls(f"a.b.{c}", pts, A64_EXPR)
    ac += _calls("a.str", a.points["str_"][2], A64_EXPR)
    ac += ["movz(x1, 1, lsl=16)", "a.movk(w1, 1, lsl=16)"]
    return {"accepted_x64.py": _corpus_file("x64", xc), "accepted_aarch64.py": _corpus_file("aarch64", ac)}


# -- prefilter check ---------------------------------------------------------------

# Classes whose values the static type of another class already covers:
# condition and bti names are strings, and a str is a label name.
_COVERED_BY = {"Cond": "Target", "Bti": "Target"}


def _covered(point: Point, accepted: set[Point]) -> bool:
    return tuple(_COVERED_BY.get(c, c) for c in point) in accepted


def prefilter_drift(max_arity: int = 2) -> list[str]:
    """Compare the oracles with and without the class level prefilter,
    for forms with at most `max_arity` operands. Returns one line per
    difference; empty when the prefilter drops nothing the encoder
    accepts (and adds nothing, which it cannot)."""
    out: list[str] = []
    pairs: list[tuple[str, dict[str, dict[int, list[Point]]], dict[str, dict[int, list[Point]]]]] = []
    xf, xu = x64_oracle(True, max_arity), x64_oracle(False, max_arity)
    pairs.append(("x64", xf.points, xu.points))
    pairs.append(("x64 .short", {k: {1: v} for k, v in xf.short.items()}, {k: {1: v} for k, v in xu.short.items()}))
    af, au = a64_oracle(True, max_arity), a64_oracle(False, max_arity)
    pairs.append(("aarch64", af.points, au.points))
    for arch, filt, unfilt in pairs:
        for py in sorted(set(filt) | set(unfilt)):
            for n in sorted(set(filt.get(py, {})) | set(unfilt.get(py, {}))):
                f = set(filt.get(py, {}).get(n, []))
                u = set(unfilt.get(py, {}).get(n, []))
                missing = sorted(p for p in u - f if not _covered(p, f))
                extra = sorted(f - u)
                if missing:
                    out.append(f"{arch} {py}/{n}: prefilter drops {missing}")
                if extra:
                    out.append(f"{arch} {py}/{n}: only with prefilter {extra}")
    return out


