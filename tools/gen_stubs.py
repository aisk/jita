X64_CLASSES = [
    "Gp8", "Gp16", "Gp32", "Gp64", "Xmm", "Ymm", "St",
    "Mem8", "Mem16", "Mem32", "Mem64", "Mem80", "Mem128", "Mem256", "MemAny",
    "int", "Target",
]  # fmt: skip


def _x64_reps() -> dict[str, list[Any]]:
    r, m = x64_regs, x64_mem

    def sized(prefix: Any) -> list[Any]:
        return [prefix[r.rbx], prefix[0x1000]]

    return {
        # al (mode R), cl (C), sil and r9b (REX), ah (high).
        "Gp8": [r.al, r.cl, r.bl, r.sil, r.r9b, r.ah],
        "Gp16": [r.ax, r.bx, r.r9w],
        "Gp32": [r.eax, r.ebx, r.r9d],
        "Gp64": [r.rax, r.rbx, r.r9],
        "Xmm": [r.xmm0, r.xmm1, r.xmm9],
        "Ymm": [r.ymm0, r.ymm1, r.ymm9],
        "St": [r.st0, r.st1],
        "Mem8": sized(m.byte),
        "Mem16": sized(m.word),
        "Mem32": sized(m.dword),
        "Mem64": sized(m.qword),
        "Mem80": sized(m.tword),
        "Mem128": sized(m.oword),
        "Mem256": sized(m.yword),
        "MemAny": sized(m.ptr),
        "int": [0, 1, 3, 127, 200, 0x1234, 0x12345678, -1, 1 << 40],
        # str and Extern classify like a Label.
        "Target": [Label("target")],
    }


X64_REPS = _x64_reps()

# Mnemonics that `encode` special-cases before template matching.
X64_SPECIAL = frozenset(["mov", "xchg", "mov64", "movabs"])


def _x64_modes() -> dict[str, list[str]]:
    return {c: [x64_encoder._classify(op, "", ()).mode for op in reps] for c, reps in X64_REPS.items()}


def _x64_opsizes() -> dict[str, str | None]:
    out: dict[str, str | None] = {}
    for c, reps in X64_REPS.items():
        sizes = {x64_encoder._classify(op, "", ()).opsize for op in reps}
        assert len(sizes) == 1, (c, sizes)
        out[c] = sizes.pop()
    return out


def _x64_matches(template: str, point: Point, modes: dict[str, list[str]], opsize: dict[str, str | None]) -> bool:
    """The template matching of `encoder._encode_template` at the class
    level: can some alternative match the modes and sizes of some
    representatives? A necessary condition for encoding, and cheap, so
    the oracle only runs on tuples that pass it. The operand size of a
    class does not depend on the representative, and a letter check that
    passes for some representative only makes this more permissive."""
    n = len(point)
    sz: str | None = None
    szmix = False
    for c in point:
        nsz = opsize[c]
        if nsz is not None:
            if sz is not None and sz != nsz:
                szmix = True
            else:
                sz = nsz
    for tm in template.split("|"):
        if not tm:
            continue
        if not all(tm[i] == "." or any(tm[i] in md for md in modes[c]) for i, c in enumerate(point)):
            continue
        szm = tm[n : tm.index(":", n)]
        prefix = szm[:1]
        if prefix == "/":
            if all(opsize[point[j - 1]] == szm[j] for j in range(1, len(szm))):
                return True
            continue
        szp = sz
        if szm == "":
            szm = "qdwb"
        if prefix == "1":
            szp = opsize[point[0]]
            szmix = False
        elif prefix == "2":
            szp = opsize[point[1]]
            szmix = False
        if not szmix and (prefix == "." or (szp is not None and szp in szm)):
            return True
    return False


def _x64_viable(template: str, n: int, modes: dict[str, list[str]], opsize: dict[str, str | None]) -> list[Point]:
    """Class tuples worth asking the encoder about for `template`."""
    per_pos: list[set[str]] = [set() for _ in range(n)]
    for tm in template.split("|"):
        if not tm:
            continue
        for i in range(n):
            ch = tm[i]
            per_pos[i].update(c for c in X64_CLASSES if ch == "." or any(ch in md for md in modes[c]))
    ordered = [sorted(p, key=X64_CLASSES.index) for p in per_pos]
    return [p for p in itertools.product(*ordered) if _x64_matches(template, p, modes, opsize)]


class X64Result:
    """Accepted points per Python name: `sigs[py][n]` for the call, and
    `short[py]` for `.short` on the rel8 branches."""

    def __init__(self) -> None:
        self.points: dict[str, dict[int, list[Point]]] = {}
        self.short: dict[str, list[Point]] = {}


@functools.cache
def x64_oracle(filtered: bool = True, max_arity: int | None = None) -> X64Result:
    """Accepted points for every x64 mnemonic. `filtered=False` skips the
    class level prefilter and asks the encoder about every class tuple
    (slow; the tests use it with `max_arity` to check the prefilter).
    `max_arity` leaves out forms with more operands."""
    modes, opsize = _x64_modes(), _x64_opsizes()

    def viable(template: str, n: int) -> Iterable[Point]:
        if filtered:
            return _x64_viable(template, n, modes, opsize)
        return itertools.product(X64_CLASSES, repeat=n)

    res = X64Result()
    memo: dict[tuple[str, int], list[Point]] = {}
    short_memo: dict[str, list[Point]] = {}
    keys: dict[str, list[int]] = {}
    for key in X64_OP:
        mn, _, n = key.rpartition("_")
        keys.setdefault(mn, []).append(int(n))
    keys["mov64"] = keys["movabs"] = [2]

    def run(mn: str, n: int, candidates: Iterable[Point], short: bool = False) -> list[Point]:
        def enc(ops: Sequence[object]) -> None:
            x64_encoder.encode(_SINK, mn, ops, short)

        return sorted(p for p in candidates if _accepts(enc, [X64_REPS[c] for c in p]))

    for mn in sorted(keys):
        py = x64_insns.PY_NAMES.get(mn, mn)
        per_n: dict[int, list[Point]] = {}
        for n in sorted(keys[mn]):
            if max_arity is not None and n > max_arity:
                continue
            if n == 0:
                per_n[0] = [()]
                continue
            if mn in X64_SPECIAL:
                per_n[n] = run(mn, n, itertools.product(X64_CLASSES, repeat=n))
                continue
            template = X64_OP[f"{mn}_{n}"]
            hit = memo.get((template, n))
            if hit is None:
                hit = memo[(template, n)] = run(mn, n, viable(template, n))
            per_n[n] = hit
        res.points[py] = per_n
        if mn in x64_insns.SHORT_BRANCHES:
            template = X64_OP[f"{mn}_1"]
            hit = short_memo.get(template)
            if hit is None:
                hit = short_memo[template] = run(mn, 1, viable(template, 1), short=True)
            res.short[py] = hit
    return res


