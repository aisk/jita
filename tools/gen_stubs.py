def generate() -> dict[Path, str]:
    """Stub path -> generated text."""
    return {
        ROOT / "jita/x64/insns.pyi": render_x64_insns(x64_oracle()),
        ROOT / "jita/x64/__init__.pyi": render_x64_init(),
        ROOT / "jita/aarch64/insns.pyi": render_a64_insns(a64_oracle()),
        ROOT / "jita/aarch64/__init__.pyi": render_a64_init(),
        ROOT / "jita/riscv64/insns.pyi": render_rv_insns(rv_oracle()),
        ROOT / "jita/riscv64/__init__.pyi": render_rv_init(),
        ROOT / "jita/loongarch64/insns.pyi": render_la_insns(la_oracle()),
        ROOT / "jita/loongarch64/__init__.pyi": render_la_init(),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only report stale stubs")
    parser.add_argument(
        "--unfiltered",
        type=int,
        metavar="N",
        help="instead of writing stubs, ask the encoder about every class tuple of up to N operands "
        "without the class level prefilter and report where the two disagree (N=2 takes a few seconds)",
    )
    args = parser.parse_args(argv)
    if args.unfiltered is not None:
        drift = prefilter_drift(args.unfiltered)
        for line in drift:
            print(line)
        return 1 if drift else 0
    stale = []
    for path, text in generate().items():
        old = path.read_text() if path.exists() else None
        if old == text:
            continue
        stale.append(path)
        if not args.check:
            path.write_text(text)
    for path in stale:
        print(f"{'stale' if args.check else 'wrote'} {path.relative_to(ROOT)}")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
